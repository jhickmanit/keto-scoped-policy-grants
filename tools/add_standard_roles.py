"""Build the hybrid OPL: the base schema plus standard roles as fixed relations.

Everything in the base OPL is kept, including Platform_role / Platform_need
for custom roles and needs. For every role in the mapping's standard_roles,
each *_Group type that covers one of its permissions gets a relation

    <role>: SubjectSet<User_Group, "Members">[]

and that group's permit for each of the role's permissions also accepts the
role's holders directly. The permission lists therefore live in the OPL, and
the mapping is the single source for both the OPL and the transform.

Usage: python3 -I tools/add_standard_roles.py MAPPING BASE_OPL > OUT_OPL
"""

import json
import re
import sys


def main(mapping_path, base_path):
    mapping = json.load(open(mapping_path))["mapping"]
    opl = open(base_path).read()
    standard = mapping["standard_roles"]
    holder = mapping["holder_namespace"]

    # (namespace, relation) -> standard role relations that grant it.
    grants = {}
    for spec in standard.values():
        for perm in spec["permissions"]:
            target = mapping["permissions"].get(perm)
            if target:
                grants.setdefault((target["namespace"], target["relation"]), []).append(spec["relation"])

    names = {spec["relation"]: f'{role} {spec.get("name", "")}'.strip() for role, spec in standard.items()}
    for ns, group in mapping["group_namespaces"].items():
        relations = sorted({r for (n, _), rs in grants.items() if n == ns for r in rs}, key=role_order)
        if not relations:
            continue
        decl = "".join(
            f"\t\t// Standard role {names[r]}: fixed in this OPL. Assign with\n"
            f"\t\t// {group}:<scope>#{r}@{holder}:<holders>#Members\n"
            f'\t\t{r} : (SubjectSet<{holder},"Members">)[]\n\n'
            for r in relations
        )
        opl = replace_once(opl, rf"(class {group} implements Namespace {{\n\trelated: \n\t{{\n)", decl, group)

    for (ns, rel), roles in sorted(grants.items()):
        direct = "".join(f"\t\t\t\tthis.related.{r}.includes(ctx.subject) || \n" for r in sorted(roles, key=role_order))
        opl = replace_once(opl, rf"(\t\tPermit_{ns}_{rel}: \(ctx\) => \n\t\t\t\(\n)", direct, f"Permit_{ns}_{rel}")

    sys.stdout.write(
        f"// GENERATED by tools/add_standard_roles.py from {base_path.rsplit('/', 1)[-1]} and "
        f"{mapping_path.rsplit('/', 1)[-1]}. Do not edit by hand.\n"
        "// Hybrid model: standard roles are fixed relations on the *_Group types below;\n"
        "// custom roles and needs keep the Platform_role / Platform_need tuple pattern.\n"
        + opl
    )


def replace_once(text, pattern, insert, what):
    out, n = re.subn(pattern, lambda m: m.group(1) + insert, text)
    if n != 1:
        sys.exit(f"expected exactly one match for {what}, found {n}")
    return out


def role_order(name):
    return int(name[1:]) if name[1:].isdigit() else 999


if __name__ == "__main__":
    main(*sys.argv[1:3])
